import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from 'pdf-lib';

const PAGE_WIDTH = 612;
const PAGE_HEIGHT = 792;
const TEST_NOTICE = 'TEST ONLY — NOT A REAL APPLICATION';

function wrapText(text: string, font: PDFFont, size: number, maxWidth: number): string[] {
  const lines: string[] = [];
  let current = '';
  for (const word of text.split(/\s+/).filter(Boolean)) {
    const candidate = current ? `${current} ${word}` : word;
    if (font.widthOfTextAtSize(candidate, size) <= maxWidth) {
      current = candidate;
    } else {
      if (current) lines.push(current);
      current = word;
    }
  }
  if (current) lines.push(current);
  return lines;
}

function drawNotice(page: PDFPage, font: PDFFont): void {
  page.drawRectangle({
    x: 36,
    y: PAGE_HEIGHT - 44,
    width: PAGE_WIDTH - 72,
    height: 22,
    color: rgb(1, 0.92, 0.9),
    borderColor: rgb(0.72, 0.15, 0.12),
    borderWidth: 1,
  });
  page.drawText(TEST_NOTICE, {
    x: 48,
    y: PAGE_HEIGHT - 37,
    size: 10,
    font,
    color: rgb(0.62, 0.08, 0.06),
  });
}

async function renderSyntheticDocument(input: {
  title: string;
  subtitle: string;
  paragraphs: string[];
}): Promise<Uint8Array> {
  const document = await PDFDocument.create();
  const page = document.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
  const regular = await document.embedFont(StandardFonts.Helvetica);
  const bold = await document.embedFont(StandardFonts.HelveticaBold);
  drawNotice(page, bold);

  page.drawText(input.title, { x: 54, y: 690, size: 20, font: bold, color: rgb(0.15, 0.15, 0.15) });
  page.drawText(input.subtitle, { x: 54, y: 662, size: 11, font: bold, color: rgb(0.45, 0.12, 0.1) });

  let y = 620;
  for (const paragraph of input.paragraphs) {
    for (const line of wrapText(paragraph, regular, 11, PAGE_WIDTH - 108)) {
      page.drawText(line, { x: 54, y, size: 11, font: regular, color: rgb(0.2, 0.2, 0.2) });
      y -= 17;
    }
    y -= 14;
  }
  page.drawText('Generated by Apovo for automated integration testing. Contains no real patient data.', {
    x: 54,
    y: 48,
    size: 8,
    font: regular,
    color: rgb(0.35, 0.35, 0.35),
  });
  return document.save();
}

export async function renderSyntheticDiagnosisLetter(input: {
  applicantName: string;
  clinician: string;
  facility: string;
  body: string;
}): Promise<Uint8Array> {
  return renderSyntheticDocument({
    title: 'Synthetic Diagnosis Confirmation',
    subtitle: 'SYNTHETIC TEST DOCUMENT',
    paragraphs: [
      `Applicant: ${input.applicantName}`,
      `Fictional clinician: ${input.clinician}`,
      `Fictional facility: ${input.facility}`,
      input.body,
    ],
  });
}

export async function renderSyntheticPersonalNote(input: {
  applicantName: string;
  body: string;
}): Promise<Uint8Array> {
  return renderSyntheticDocument({
    title: 'Synthetic Personal Note',
    subtitle: 'FICTIONAL STORY FOR TESTING ONLY',
    paragraphs: [`Applicant: ${input.applicantName}`, input.body],
  });
}

export async function markPdfAsSyntheticTest(bytes: Uint8Array): Promise<Uint8Array> {
  const document = await PDFDocument.load(bytes);
  const bold = await document.embedFont(StandardFonts.HelveticaBold);
  for (const page of document.getPages()) {
    const { width, height } = page.getSize();
    page.drawRectangle({
      x: 18,
      y: height - 19,
      width: width - 36,
      height: 14,
      color: rgb(1, 0.94, 0.92),
      opacity: 0.94,
    });
    page.drawText(TEST_NOTICE, {
      x: 25,
      y: height - 15,
      size: 7,
      font: bold,
      color: rgb(0.68, 0.08, 0.06),
    });
  }
  return document.save();
}

